//! Generates two things the crate includes:
//!
//! - the Weir rule module (`src/linting/weir_rules/de/*.weir`, one rule per file, with one
//!   test per rule), and
//! - the dictionary pack slot: `data/german.pack` if it exists (see `just bake-pack`), else an
//!   empty file, in which case the dictionary is expanded from the word list at first use.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    weir_rules(&out_dir);
    pack(&out_dir);
}

fn pack(out_dir: &Path) {
    let source = Path::new("data/german.pack");
    println!("cargo:rerun-if-changed={}", source.display());
    let dest = out_dir.join("german.pack");
    match fs::read(source) {
        Ok(bytes) => fs::write(&dest, bytes).unwrap(),
        Err(_) => fs::write(&dest, b"").unwrap(),
    }
    println!("cargo:rustc-env=GERMAN_PACK_FILE={}", dest.display());
}

fn weir_rules(out_dir: &Path) {
    let dir = Path::new("src/linting/weir_rules/de")
        .canonicalize()
        .unwrap();
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut files: Vec<PathBuf> = fs::read_dir(&dir)
        .unwrap()
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.is_file() && p.extension().is_some_and(|e| e == "weir"))
        .collect();
    files.sort();

    let names: Vec<String> = files
        .iter()
        .map(|f| {
            println!("cargo:rerun-if-changed={}", f.display());
            f.file_stem().unwrap().to_string_lossy().to_string()
        })
        .collect();

    let source_of = |name: &str| {
        format!("include_str!(concat!(env!(\"GERMAN_WEIR_RULE_DIR\"), \"/{name}.weir\"))")
    };

    let mut code = String::new();
    code.push_str("// Generated by build.rs - do not edit.\n\n");
    code.push_str("use harper_core::linting::LintGroup;\nuse harper_core::weir::WeirLinter;\n\n");
    code.push_str("/// Every German Weir rule, all enabled.\n");
    code.push_str(
        "pub fn lint_group() -> LintGroup {\n    let mut group = LintGroup::default();\n\n",
    );
    for name in &names {
        code.push_str(&format!(
            "    let linter = WeirLinter::new({}).unwrap();\n",
            source_of(name)
        ));
        code.push_str("    match linter.into_sentence_linter() {\n");
        code.push_str(&format!(
            "        Ok(linter) => group.add_sentence_expr_linter(\"{name}\", linter),\n"
        ));
        code.push_str(&format!(
            "        Err(linter) => group.add_chunk_expr_linter(\n            \"{name}\",\n            linter.into_chunk_linter().unwrap_or_else(|_| unreachable!()),\n        ),\n"
        ));
        code.push_str("    };\n\n");
    }
    code.push_str("    group.set_all_rules_to(Some(true));\n    group\n}\n");

    code.push_str(
        "\n#[cfg(test)]\nmod tests {\n    use harper_core::weir::{TestResult, WeirLinter};\n",
    );
    for name in &names {
        code.push_str(&format!(
            "\n    /// The `test` and `allows` lines in {name}.weir.\n    #[test]\n    fn run_tests_for_{}() {{\n        let mut linter = WeirLinter::new({}).unwrap();\n        assert_eq!(Vec::<TestResult>::new(), linter.run_tests());\n    }}\n",
            snake(name),
            source_of(name)
        ));
    }
    code.push_str("}\n");

    let dest = out_dir.join("german_weir_rules.rs");
    fs::write(&dest, code).unwrap();
    println!("cargo:rustc-env=GERMAN_WEIR_RULE_DIR={}", dir.display());
    println!("cargo:rustc-env=GERMAN_WEIR_RULE_LIST={}", dest.display());
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_uppercase() {
            if i != 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}
